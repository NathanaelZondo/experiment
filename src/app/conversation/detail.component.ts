export class ConversationDetailComponent implements OnInit {
  private service = inject(ConversationService);

  // State tracking
  newMessage = '';
  isSending = false;
  isGenerating = false;

  // Control state
  tempConfig = 0.7;
  topPConfig = 1;
  topKConfig = -1;
  repeatPenaltyConfig = 1.05;
  maxTokensConfig = 4096;
  reasoningModeConfig = 'disabled';

  // Cached selected conversation
  private lastSelectedId: string | null = null;

  // Derived states using signal values
  get canSend(): boolean {
    return !!this.service.selectedId();
  }

  get canGenerateRegenerate(): boolean {
    const messages = this.service.getMessages();
    if (messages.length === 0) return false;
    const lastMsg = messages[messages.length - 1];
    return lastMsg.role === 'assistant';
  }

  get canClear(): boolean {
    const messages = this.service.getMessages();
    return messages.length > 0;
  }

  get canResetConfig(): boolean {
    return !!this.service.selectedId();
  }

  /** Get the selected conversation from service */
  get selectedConversation(): import('../conversation.service').Conversation | null {
    return this.service.getSelected();
  }

  /** Check if a conversation is selected */
  private isSelected(): boolean {
    return this.service.selectedId() !== null;
  }

  ngOnInit(): void {
    // Subscribe to selection changes using signal value changes
    const id = this.service.selectedId();
    if (id && id !== this.lastSelectedId) {
      this.loadConversation(id);
      this.lastSelectedId = id;
    }

    // In a real app, would set up proper subscription here
    // For now just update state once
    this.updateCanSendState();
  }

  /** Load conversation messages into local state */
  private loadConversation(id: string): void {
    // Messages are stored in the service signals, just need to track selection
    this.service.selectedId.set(id);
  }

  /** Update send button enable/disable state */
  private updateCanSendState(): void {
    // canSend is a derived getter based on signal value
  }

  /** Send a message */
  sendMessage(): void {
    if (!this.newMessage.trim() || !this.canSend) return;

    // Add user message to the current conversation
    this.service.addUserMessage(this.newMessage);

    // Set sending state
    this.isSending = true;

    // Clear the input
    this.newMessage = '';

    // TODO: In a real app, this would call the LM Studio streaming API
    // For now, we simulate with a timeout
    this.simulateAssistantResponse();
  }

  /** Simulate assistant response with streaming */
  private simulateAssistantResponse(): void {
    // Add a placeholder assistant message immediately
    this.service.addAssistantMessage('Thinking...');

    // Set generation flag
    this.isGenerating = true;

    // Simulate streaming after delay
    setTimeout(() => {
      // Remove the "Thinking..." placeholder and add real response
      this.service.regenerateLatestResponse();

      // Update generation state
      this.isGenerating = false;
      this.isSending = false;

      // In a real app, we would stream the response live here
    }, 1500);
  }

  /** System prompt change handler */
  onSystemPromptChange(event: any): void {
    const value = event.target?.value ?? '';
    this.service.setSystemPrompt(value);
  }

  /** System prompt change handler - keyboard */
  onKeyDown(event: KeyboardEvent): void {
    if (event.shiftKey && event.key === 'Enter') {
      // Shift+Enter: insert newline at cursor position
      const text = this.newMessage;
      const start = (event.target as HTMLInputElement).selectionStart ?? 0;
      const end = (event.target as HTMLInputElement).selectionEnd ?? start;

      // Insert \n at cursor position
      const prefix = text.substring(0, start);
      const suffix = text.substring(end);
      ;(event.target as HTMLInputElement).value =
        prefix + '\n' + suffix;
      this.newMessage = (event.target as HTMLInputElement).value;
      event.preventDefault();
    } else if (!event.shiftKey && event.key === 'Enter') {
      // Plain Enter: send message (prevent default form submission)
      event.preventDefault();
      this.sendMessage();
    }
  }

  /** Control change handler */
  onControlChange(
    field: keyof GenerationConfig,
    event: any,
  ): void {
    const value = event.target?.value ?? '';
    const numValue = Number(value);

    // Validation against supported ranges
    switch (field) {
      case 'temperature':
        if (numValue >= 0 && numValue <= 2) {
          this.tempConfig = numValue;
        }
        break;
      case 'topP':
        if (numValue >= 0 && numValue <= 1) {
          this.topPConfig = numValue;
        }
        break;
      case 'topK':
        if (Number.isInteger(numValue) || numValue === -1) {
          this.topKConfig = numValue;
        }
        break;
      case 'repeatPenalty':
        if (numValue > 0) {
          this.repeatPenaltyConfig = numValue;
        }
        break;
      case 'maxTokens':
        if (numValue >= 1) {
          this.maxTokensConfig = numValue;
        }
        break;
      case 'reasoningMode':
        if (
          value === 'disabled' ||
          value === 'enabled' ||
          value === 'auto'
        ) {
          this.reasoningModeConfig = value;
        }
        break;
    }
  }

  /** Clear conversation */
  clearConversation(): void {
    if (confirm('Clear all messages in this conversation?')) {
      this.service.clearAll();
    }
  }

  /** Regenerate the latest assistant response */
  regenerateLatestResponse(): boolean {
    return this.service.regenerateLatestResponse();
  }

  /** Reset generation settings to defaults */
  resetGenerationConfig(): void {
    this.tempConfig = 0.7;
    this.topPConfig = 1;
    this.topKConfig = -1;
    this.repeatPenaltyConfig = 1.05;
    this.maxTokensConfig = 4096;
    this.reasoningModeConfig = 'disabled';
    this.service.resetGenerationConfig();
  }
}